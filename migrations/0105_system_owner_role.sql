-- SEC-02: режим инстанса (ТЗ §11). Экземпляр разворачивается либо у обязанной
-- ИТ-компании, либо у образовательной организации, и от этого зависит, кого
-- система считает контрагентом. До этого режим нигде не хранился, а реестр
-- партнёров выбирался по типу профиля пользователя — то есть у разных
-- пользователей одного экземпляра он мог отличаться.
INSERT INTO settings(key,value)
VALUES ('system_owner_role','IT_COMPANY')
ON CONFLICT (key) DO NOTHING;
