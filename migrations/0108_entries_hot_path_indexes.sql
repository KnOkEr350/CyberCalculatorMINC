-- DASH-06 / QA-10: бюджет ответа дашборда 500 мс на согласованном объёме.
--
-- Граница зачёта (entry_eligibility) для каждой записи проверяет, что по
-- соглашению закрыты все обязательные виды: коррелированный подзапрос ищет
-- записи по (соглашение, год, период, вид). Без составного индекса он шёл по
-- индексу вида и отсеивал тысячи чужих строк на каждую проверяемую запись:
-- 10 000 записей арендатора давали около 20 секунд. С индексом — десятки
-- миллисекунд.
--
-- Индекс частичный: проверка учитывает только записи с положительной суммой.
CREATE INDEX IF NOT EXISTS idx_entries_agreement_period_category
  ON entries (agreement_id, report_year, period_type, category_code)
  WHERE amount_rub > 0;

-- Выборки дашборда и проекции всегда ограничены арендатором и годом.
CREATE INDEX IF NOT EXISTS idx_entries_company_period
  ON entries (it_company_id, report_year, period_type);
